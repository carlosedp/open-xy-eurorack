# Generates machines/chimes/tables.h from the formulas in upstream Rings'
# rings/resources/lookup_tables.py, quantized to the fixed-point formats the
# machine uses. From the repository root:
#   python tools/chimes_tables.py machines/chimes/tables.h
import sys
import numpy

out = []
def emit(name, kind, values, comment):
    out.append('// ' + comment)
    out.append('const %s %s[%d] = {' % (kind, name, len(values)))
    line = '    '
    for i, v in enumerate(values):
        item = '%d,' % v
        if len(line) + len(item) + 1 > 110:
            out.append(line.rstrip())
            line = '    '
        line += item + ' '
    out.append(line.rstrip())
    out.append('};')
    out.append('')

def q(values, bits, lo=None, hi=None):
    r = numpy.round(numpy.asarray(values, dtype=numpy.float64) * (1 << bits)).astype(numpy.int64)
    if lo is not None: r = numpy.maximum(r, lo)
    if hi is not None: r = numpy.minimum(r, hi)
    return [int(x) for x in r]

# Stiffness, as upstream: Structure 0..1 in 256 steps, Q26.
structure = numpy.arange(0, 257) / 256.0
stiffness = structure + 0
for i, g in enumerate(structure):
    if g < 0.25:
        g = 0.25 - g
        stiffness[i] = -g * 0.25
    elif g < 0.3:
        stiffness[i] = 0.0
    elif g < 0.9:
        g -= 0.3
        g /= 0.6
        stiffness[i] = 0.01 * 10 ** (g * 2.005) - 0.01
    else:
        g -= 0.9
        g /= 0.1
        g *= g
        stiffness[i] = 1.5 - numpy.cos(g * numpy.pi) / 2.0
stiffness[-1] = 2.0
stiffness[-2] = 2.0
emit('kStiffness', 'opxy::i32', q(stiffness, 26),
     'Rings lut_stiffness: per-partial stretch by Structure (256 steps), Q26.')

# The damping filter's delay in periods, atan(x) / pi, for x = tan(pi f) / g in
# 0..1: Rings' lut_svf_shift (2 atan(1 / ratio) / 2 pi) with the ratio taken
# through the filter's frequency warping. Q31.
x = numpy.arange(0, 257) / 256.0
emit('kArctan', 'opxy::i32', q(numpy.arctan(x) / numpy.pi, 31),
     'atan(x) / pi for x = 0..1 in 256 steps, Q31: the damping filter\'s delay in periods.')

# 2^(k/256), Q30, for exponentials.
emit('kPow2', 'opxy::u32', q(2.0 ** (numpy.arange(0, 257) / 256.0), 30),
     '2^(k/256) for k = 0..256, Q30.')

# 1 / (1 + k/256), Q31, for reciprocals of normalized mantissas.
emit('kReciprocal', 'opxy::u32', q(1.0 / (1.0 + numpy.arange(0, 257) / 256.0), 31),
     '1 / (1 + k/256) for k = 0..256, Q31.')

# tan(pi f) for f = 0..0.5 in 512 steps, Q28, clamped below 8 (FREQUENCY_ACCURATE).
f = numpy.arange(0, 513) / 1024.0
emit('kTan', 'opxy::i32', q(numpy.tan(numpy.pi * numpy.minimum(f, 0.4999)), 28, hi=(8 << 28) - 1),
     'tan(pi f) for f = 0..0.5 in 512 steps, Q28, clamped below 8.')

# stmlib SoftLimit x (27 + x^2) / (27 + 9 x^2) for x = 0..4 in 256 steps, Q31; 1 from x = 3.
x = numpy.arange(0, 257) / 64.0
soft = numpy.where(x < 3.0, x * (27 + x * x) / (27 + 9 * x * x), 1.0)
emit('kSoftLimit', 'opxy::i32', q(soft, 31, hi=2147483647),
     'stmlib SoftLimit for x = 0..4 in 256 steps, Q31; 1 from x = 3.')

# Rings' two-string chords (BRYAN_CHORDS, polyphony 4), semitones from the note, Q16.
chords = [
    [0.0, -12.0],
    [0.0, 2.0],
    [0.0, 3.0],
    [0.0, 4.0],
    [0.0, 5.0],
    [0.0, 7.0],
    [0.0, 9.0],
    [0.0, 10.0],
    [0.0, 11.0],
    [0.0, 12.0],
    [-12.0, 12.0],
]
out.append('// Rings\' two-string chords (BRYAN_CHORDS at polyphony 4), semitones from the note, Q16:')
out.append('// octave below, 2nd, minor 3rd, major 3rd, 4th, 5th, 6th, minor 7th, major 7th,')
out.append('// octave, and octaves either side.')
out.append('const opxy::i32 kChords[11][2] = {')
for c in chords:
    out.append('    {' + ', '.join('%d' % round(v * 65536) for v in c) + '},')
out.append('};')
out.append('')

header = '''#pragma once
#include <opxy/types.hpp>

// Lookup tables from upstream Rings' rings/resources/lookup_tables.py formulas
// (MIT, Emilie Gillet; see vendor/LICENSE), quantized to Chimes' fixed-point
// formats. Generated by tools/chimes_tables.py; regenerate rather than edit.
namespace chimes {
'''
with open(sys.argv[1], 'w', newline='\n') as fh:
    fh.write(header + '\n'.join(out) + '}  // namespace chimes\n')
