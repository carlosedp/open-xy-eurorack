# Generates the tables.h of the machines after Clouds, Cirrus and Stratus, from
# the formulas in upstream Clouds' clouds/resources/lookup_tables.py, quantized
# to the fixed-point formats they use and rescaled from Clouds' 32 kHz to the
# OP-XY's 44.1 kHz. The two differ only in their namespace. From the
# repository root:
#   python tools/clouds_tables.py machines/cirrus/tables.h
#   python tools/clouds_tables.py machines/stratus/tables.h
import sys
from pathlib import Path
import numpy

out = []
def emit(name, kind, values, comment):
    out.append('// ' + comment)
    out.append('const %s %s[%d] = {' % (kind, name, len(values)))
    line = '    '
    for i, v in enumerate(values):
        item = '%d,' % v
        if len(line) + len(item) + 1 > 110:
            out.append(line.rstrip())
            line = '    '
        line += item + ' '
    out.append(line.rstrip())
    out.append('};')
    out.append('')

def q(values, bits, lo=None, hi=None):
    r = numpy.round(numpy.asarray(values, dtype=numpy.float64) * (1 << bits)).astype(numpy.int64)
    if lo is not None: r = numpy.maximum(r, lo)
    if hi is not None: r = numpy.minimum(r, hi)
    return [int(x) for x in r]

RATE = 44100.0 / 32000.0  # the OP-XY's sample rate over Clouds'

# 2^(k/256), Q30, for exponentials.
emit('kPow2', 'opxy::u32', q(2.0 ** (numpy.arange(0, 257) / 256.0), 30),
     '2^(k/256) for k = 0..256, Q30.')

# 1 / (1 + k/256), Q31, for reciprocals of normalized mantissas.
emit('kReciprocal', 'opxy::u32', q(1.0 / (1.0 + numpy.arange(0, 257) / 256.0), 31),
     '1 / (1 + k/256) for k = 0..256, Q31.')

# stmlib SoftLimit x (27 + x^2) / (27 + 9 x^2) for x = 0..4 in 256 steps, Q31; 1 from x = 3.
x = numpy.arange(0, 257) / 64.0
soft = numpy.where(x < 3.0, x * (27 + x * x) / (27 + 9 * x * x), 1.0)
emit('kSoftLimit', 'opxy::i32', q(soft, 31, hi=2147483647),
     'stmlib SoftLimit for x = 0..4 in 256 steps, Q31; 1 from x = 3.')

# Clouds lut_window, the grain's raised-cosine window, in 256 steps instead of
# 4096 (linear interpolation keeps it within 2e-5), Q15. The last entry repeats
# so that a full-scale index reads past the end safely.
t = numpy.arange(0, 257) / 256.0
window = q(1.0 - (numpy.cos(t * numpy.pi) + 1) / 2, 15, hi=32767)
emit('kWindow', 'opxy::i32', window + [window[-1]],
     'Clouds lut_window: 1 - (cos(pi t) + 1) / 2 for t = 0..1 in 256 steps, Q15.')

# Clouds lut_xfade_in and lut_xfade_out, the Blend crossfade, Q31. The last
# entry repeats, so that full scale reads entry 16 exactly.
t = numpy.arange(0, 17) / 16.0
t = numpy.clip(1.04 * t - 0.02, 0, 1) * numpy.pi / 2
fade_in, fade_out = q(numpy.sin(t) * 2 ** -0.5, 31), q(numpy.cos(t) * 2 ** -0.5, 31)
emit('kFadeIn', 'opxy::i32', fade_in + [fade_in[-1]], 'Clouds lut_xfade_in, Q31.')
emit('kFadeOut', 'opxy::i32', fade_out + [fade_out[-1]], 'Clouds lut_xfade_out, Q31.')

# Clouds lut_grain_size, floor(1024 2^(4 size)) samples at 32 kHz, as the same
# durations at 44.1 kHz. Q8 samples.
size = numpy.arange(0, 257) / 256.0 * 4
emit('kGrainSize', 'opxy::i32', q(numpy.floor(1024 * 2 ** size) * RATE, 8),
     'Clouds lut_grain_size at 44.1 kHz: 1024 2^(4 size) samples at 32 kHz, Q8 samples.')

# The reverb's damping low-pass, 0.6 + 0.37 feedback per sample at 32 kHz, as
# the same time constant at 44.1 kHz: 1 - (1 - c)^(32 / 44.1). By Feedback in
# 256 steps, Q31.
feedback = numpy.arange(0, 257) / 256.0
emit('kReverbDamping', 'opxy::i32', q(1 - (1 - (0.6 + 0.37 * feedback)) ** (1 / RATE), 31),
     'Clouds\' reverb damping, 0.6 + 0.37 feedback at 32 kHz, at 44.1 kHz; Q31.')

machine = Path(sys.argv[1]).parent.name  # the machine's folder: its id and namespace
text = ('// Generated by tools/clouds_tables.py from upstream Clouds\' lookup_tables.py.\n'
        '// Do not edit: run python tools/clouds_tables.py machines/%s/tables.h\n'
        '#pragma once\n#include <opxy/types.hpp>\n\nnamespace %s {\n' % (machine, machine) + '\n'.join(out) +
        '}  // namespace %s\n' % machine)
with open(sys.argv[1], 'w', newline='\n') as f:
    f.write(text)
